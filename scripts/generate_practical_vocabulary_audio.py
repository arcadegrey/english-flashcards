"""Local Kokoro four-voice audio for the practical replacement batch; resumable."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'public/audio-updates/2026-10-25'
VOICES = ['af_bella', 'am_michael', 'bf_emma', 'bm_george']


def digest(value):
    return hashlib.sha256(value).hexdigest()


def main():
    import numpy as np
    from kokoro import KPipeline
    from generate_kokoro_word_audio import write_mp3

    words = json.loads((ROOT / 'data/vocabulary-replacement/practical-2026-10-25.json').read_text())
    manifest_path = OUTPUT / 'manifest.json'
    previous = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
    files = {item['path']: item for item in previous.get('files', [])}
    expected = {
        f"/audio-updates/2026-10-25/{field}/{voice}/{word['id']}-{digest((word[field] + '|kokoro-82m|24k|v1').encode())[:12]}.mp3"
        for word in words for field in ['word', 'example'] for voice in VOICES
    }
    for url in list(files):
        if url not in expected:
            obsolete = ROOT / 'public' / url.lstrip('/')
            obsolete.resolve().relative_to(OUTPUT.resolve())
            obsolete.unlink(missing_ok=True)
            del files[url]
    updates, pipelines = {}, {}
    for voice in VOICES:
        language = 'b' if voice.startswith(('bf_', 'bm_')) else 'a'
        if language not in pipelines:
            # Use the same local CPU pipeline as existing production recordings.
            pipelines[language] = KPipeline(lang_code=language, repo_id='hexgrad/Kokoro-82M')
        for word in words:
            for field in ['word', 'example']:
                text = word[field]
                revision = digest((text + '|kokoro-82m|24k|v1').encode())[:12]
                path = OUTPUT / field / voice / f"{word['id']}-{revision}.mp3"
                url = '/' + path.relative_to(ROOT / 'public').as_posix()
                prior = files.get(url)
                if not (prior and path.exists() and digest(path.read_bytes()) == prior['sha256']):
                    chunks, phones = [], []
                    for _, phonemes, audio in pipelines[language](text, voice=voice, speed=0.92 if field == 'word' else 0.96):
                        chunks.append(np.asarray(audio, dtype=np.float32))
                        phones.append(phonemes)
                    if not chunks:
                        raise RuntimeError(f'No audio for {word["id"]} {field}')
                    audio = np.concatenate(chunks)
                    temporary = path.with_suffix('.tmp.mp3')
                    write_mp3(audio, temporary, '24')
                    temporary.replace(path)
                    files[url] = dict(id=word['id'], field=field, voice=voice, text=text,
                                      textSha256=digest(text.encode()), path=url,
                                      sha256=digest(path.read_bytes()), bytes=path.stat().st_size,
                                      seconds=round(len(audio) / 24000, 3), phonemes=' '.join(phones))
                    OUTPUT.mkdir(parents=True, exist_ok=True)
                    # Checkpoint every recording so an interrupted batch is resumable.
                    manifest_path.write_text(json.dumps(dict(batch='2026-10-25', voices=VOICES, files=list(files.values())), ensure_ascii=False, indent=2) + '\n')
                updates.setdefault(str(word['id']), {})[field] = dict(text=text, revision=revision)
            print(f'{voice} {word["id"]} OK ({len(files)}/1976)', flush=True)
    assert len(files) == 1976
    manifest_path.write_text(json.dumps(dict(batch='2026-10-25', voices=VOICES, files=list(files.values())), ensure_ascii=False, indent=2) + '\n')
    (ROOT / 'shared/practicalVocabularyAudio.js').write_text(
        '// Generated by scripts/generate_practical_vocabulary_audio.py.\n'
        + 'export const PRACTICAL_VOCABULARY_AUDIO = ' + json.dumps(updates, ensure_ascii=False, indent=2) + ';\n')


if __name__ == '__main__':
    main()
