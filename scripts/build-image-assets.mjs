import sharp from 'sharp';
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const sourceDir = path.join(root, 'public/images/ui-assets');
const outputDir = path.join(root, 'public/images/optimized');
await mkdir(outputDir, { recursive: true });
const writeChanged = async (file, contents) => {
  const previous = await readFile(file).catch(error => {
    if (error.code !== 'ENOENT') throw error;
    return null;
  });
  if (!previous?.equals(Buffer.from(contents))) await writeFile(file, contents);
};

const manifest = {};
const generated = new Set();
let originalBytes = 0;
let optimizedBytes = 0;
for (const name of (await readdir(sourceDir)).sort()) {
  if (!name.endsWith('.png') || /(?:-source|-alpha|sprite[^/]*)\.png$/.test(name)) continue;
  const input = await readFile(path.join(sourceDir, name));
  const width = name === 'mobile-learning-landscape-v1.png' ? 960 : 640;
  const { data, info } = await sharp(input)
    .resize({ width, withoutEnlargement: true })
    .webp({ quality: 84, alphaQuality: 95, effort: 5 })
    .toBuffer({ resolveWithObject: true });
  const hash = createHash('sha256').update(data).digest('hex').slice(0, 16);
  const file = `${path.basename(name, '.png')}-${hash}.webp`;
  await writeChanged(path.join(outputDir, file), data);
  generated.add(file);
  manifest[`/images/ui-assets/${name}`] = {
    src: `/images/optimized/${file}`, width: info.width, height: info.height,
    bytes: data.length, originalBytes: input.length,
  };
  originalBytes += input.length;
  optimizedBytes += data.length;
}

for (const file of await readdir(outputDir)) {
  if (/^[\w-]+-[a-f0-9]{16}\.webp$/.test(file) && !generated.has(file)) await rm(path.join(outputDir, file));
}
await writeChanged(path.join(root, 'src/data/imageAssets.json'), `${JSON.stringify(manifest, null, 2)}\n`);
const landscape = manifest['/images/ui-assets/mobile-learning-landscape-v1.png'].src;
await writeChanged(path.join(root, 'src/styles/image-assets.css'),
  `/* Generated by scripts/build-image-assets.mjs. */\n:root { --study-landscape-image: url('${landscape}'); }\n`);
console.log(`Images: ${Object.keys(manifest).length} assets, ${originalBytes} → ${optimizedBytes} bytes (${(100 * (1 - optimizedBytes / originalBytes)).toFixed(1)}% smaller)`);
