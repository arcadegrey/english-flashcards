"""Generate only the reviewed corrections, without overwriting legacy CDN audio.

Run with .venv-kokoro/bin/python scripts/generate_vocabulary_repair_audio.py.
The small versioned asset set is committed and shipped with the frontend.
"""
import argparse
import hashlib
import json
from pathlib import Path

DEFAULT_VOICES = ['af_bella', 'am_michael', 'bf_emma', 'bm_george']

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'public/audio-updates/2026-10-24'


def digest(value):
    return hashlib.sha256(value).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dry-run', action='store_true')
    args = parser.parse_args()
    reviews = json.loads((ROOT / 'data/vocabulary-audit-reviews.json').read_text())['reviews']
    jobs = []
    for review in reviews:
        for field in ('word', 'example'):
            before, after = review['before'], review['after']
            # Les and Sara also need their corrected personal-name pronunciations.
            if before[field] == after[field] and not (field == 'word' and after['word'] in ('les', 'sara')):
                continue
            text = after[field]
            synthesis = text
            if field == 'word' and text == 'les':
                synthesis = '[Les](/lˈɛz/)'
            elif field == 'word' and text == 'sara':
                synthesis = '[Sara](/sˈɛɹə/)'
            revision = digest((synthesis + '|kokoro-82m|24k|v1').encode())[:12]
            jobs.append(dict(id=review['id'], field=field, text=text, synthesis=synthesis, revision=revision))
    print(f'{len(jobs)} texts × {len(DEFAULT_VOICES)} voices = {len(jobs) * len(DEFAULT_VOICES)} files', flush=True)
    if args.dry_run:
        print(json.dumps(jobs, ensure_ascii=False, indent=2))
        return
    import numpy as np
    from generate_kokoro_word_audio import get_pipeline, lang_code_for_voice, write_mp3

    pipelines, files, updates = {}, [], {}
    manifest_path = OUTPUT / 'manifest.json'
    previous = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
    previous_files = {item['path']: item for item in previous.get('files', [])}
    for voice in DEFAULT_VOICES:
        pipeline = get_pipeline(lang_code_for_voice(voice), pipelines)
        for job in jobs:
            path = OUTPUT / job['field'] / voice / f"{job['id']}-{job['revision']}.mp3"
            url = '/' + path.relative_to(ROOT / 'public').as_posix()
            prior = previous_files.get(url)
            if prior and path.exists() and prior['sha256'] == digest(path.read_bytes()):
                files.append(prior)
            else:
                chunks, phonemes = [], []
                for _, phones, audio in pipeline(job['synthesis'], voice=voice, speed=0.92 if job['field'] == 'word' else 0.96):
                    chunks.append(np.asarray(audio, dtype=np.float32))
                    phonemes.append(phones)
                if not chunks:
                    raise RuntimeError(f'No audio: {job}')
                audio = np.concatenate(chunks)
                temporary = path.with_suffix('.tmp.mp3')
                write_mp3(audio, temporary, '24')
                temporary.replace(path)
                files.append(dict(id=job['id'], field=job['field'], voice=voice, text=job['text'],
                                  synthesis=job['synthesis'], textSha256=digest(job['text'].encode()),
                                  path=url, sha256=digest(path.read_bytes()), bytes=path.stat().st_size,
                                  seconds=round(len(audio) / 24000, 3), phonemes=' '.join(phonemes)))
            updates.setdefault(str(job['id']), {})[job['field']] = dict(text=job['text'], revision=job['revision'])
            print(f'{voice} {job["field"]} {job["id"]} OK', flush=True)
    manifest_path.write_text(json.dumps(dict(batch='2026-10-24', voices=DEFAULT_VOICES, files=files), ensure_ascii=False, indent=2) + '\n')
    (ROOT / 'shared/vocabularyAudioUpdates.js').write_text(
        '// Generated by scripts/generate_vocabulary_repair_audio.py; text match protects historical snapshots.\n'
        + 'export const VOCABULARY_AUDIO_UPDATES = ' + json.dumps(updates, ensure_ascii=False, indent=2) + ';\n')


if __name__ == '__main__':
    main()
